import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contentRoot = path.resolve(process.argv[2] || path.join(root, 'content'));
const output = path.resolve(process.argv[3] || path.join(root, 'src/Generated/Content.elm'));
const schemas = {
  sections: ['id', 'heading', 'subtitle', 'plateMeta', 'plateTitle', 'plateCaption', 'lead'],
  journal: ['id', 'number', 'category', 'title', 'summary']
};
function readLocale(locale, kind) {
  const directory = path.join(contentRoot, locale, kind);
  return fs.readdirSync(directory).filter(name => name.endsWith('.md')).sort().map(name => {
    const file = path.join(directory, name);
    const text = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
    const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text);
    if (!match) throw new Error(`${file}: expected front matter between --- lines`);
    const meta = {};
    for (const line of match[1].split('\n')) {
      const field = /^([A-Za-z]+):\s*(.*)$/.exec(line);
      if (!field || !schemas[kind].includes(field[1])) throw new Error(`${file}: invalid metadata: ${line}`);
      if (Object.hasOwn(meta, field[1])) throw new Error(`${file}: duplicate ${field[1]}`);
      meta[field[1]] = field[2].trim();
    }
    for (const key of schemas[kind]) if (!meta[key]) throw new Error(`${file}: missing ${key}`);
    if (meta.id !== path.basename(name, '.md')) throw new Error(`${file}: id must match filename`);
    if (!match[2].trim()) throw new Error(`${file}: empty Markdown body`);
    return { ...meta, body: match[2].trim() };
  });
}
const locales = {};
for (const locale of ['en', 'es']) {
  locales[locale] = {};
  for (const kind of Object.keys(schemas)) locales[locale][kind] = readLocale(locale, kind);
  if (locales[locale].sections.length !== 1 || locales[locale].sections[0].id !== 'magic') {
    throw new Error(`${locale}: this first-stage pipeline supports sections/magic.md only`);
  }
  const numbers = locales[locale].journal.map(entry => entry.number);
  if (new Set(numbers).size !== numbers.length) throw new Error(`${locale}: duplicate journal number`);
  locales[locale].journal.sort((a, b) => a.number.localeCompare(b.number, 'en', { numeric: true }));
}
for (const kind of Object.keys(schemas)) {
  const ids = locale => locales[locale][kind].map(entry => entry.id).sort();
  if (JSON.stringify(ids('en')) !== JSON.stringify(ids('es'))) throw new Error(`${kind}: English/Spanish IDs must match`);
}
for (const entry of locales.en.journal) {
  if (locales.es.journal.find(other => other.id === entry.id).number !== entry.number) throw new Error(`${entry.id}: translated journal numbers must match`);
}
// Elm string literals require Unicode escapes for control characters, rather than JSON escapes.
const elmString = value => '"' + [...value].map(char => {
  if (char === '"') return '\\"';
  if (char === '\\') return '\\\\';
  if (char === '\n') return '\\n';
  if (char === '\r') return '\\r';
  if (char === '\t') return '\\t';
  const code = char.codePointAt(0);
  return code < 32 || code === 127 ? `\\u{${code.toString(16)}}` : char;
}).join('') + '"';
const record = (entry, keys) => '{ ' + keys.map(key => `${key} = ${elmString(entry[key])}`).join(', ') + ' }';
const magicKeys = [...schemas.sections.filter(key => key !== 'id'), 'body'];
const journalKeys = [...schemas.journal, 'body'];
const alias = (name, keys) => `type alias ${name} =\n    { ${keys.map(key => `${key} : String`).join('\n    , ')}\n    }`;
const source = `module Generated.Content exposing (Magic, JournalEntry, magic, journal)

-- Generated by scripts/generate-content.mjs. Edit content/en and content/es instead.
import I18n exposing (Language(..))

${alias('Magic', magicKeys)}

${alias('JournalEntry', journalKeys)}

magic : Language -> Magic
magic language =
    case language of
        English ->
            ${record(locales.en.sections[0], magicKeys)}

        Spanish ->
            ${record(locales.es.sections[0], magicKeys)}

journal : Language -> List JournalEntry
journal language =
    case language of
        English ->
            [ ${locales.en.journal.map(entry => record(entry, journalKeys)).join('\n            , ')} ]

        Spanish ->
            [ ${locales.es.journal.map(entry => record(entry, journalKeys)).join('\n            , ')} ]
`;
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, source);
console.log('Validated English/Spanish content and generated ' + path.relative(root, output));
