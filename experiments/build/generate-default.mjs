import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';

const root = fileURLToPath(new URL('../', import.meta.url));
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'andara-default-map-'));
try {
  const output = path.join(temporary, 'generator.js');
  execFileSync(path.join(root, '../node_modules/.bin/elm'), ['make', 'build/GenerateDefault.elm', '--optimize', '--output=' + output], { cwd: root, stdio: 'inherit' });
  const { Elm } = createRequire(import.meta.url)(output);
  const examples = ["!(a & b)", "a | b", "a & b", "!(a | b)", "(a | b) & !(a & b)", "!a | b", "(!s & a) | (s & b)", "(a & b) | (a & c) | (b & c)", "(a | b) & !c", "(a & b) | (c & d) | (e & f)", "a | !a", "a & !a"];
  const tilings = [];
  for (const source of examples) {
    const tiling = await new Promise(resolve => Elm.GenerateDefault.init({flags: source}).ports.report.subscribe(resolve));
    if (tiling.tiles.some(tile => tile.area + 1e-6 < tiling.width * tiling.height / 800)) throw new Error('Minimum region area not reached: ' + source);
    tilings.push(tiling);
    console.log('Precomputed ' + source + ' (' + tiling.tiles.length + ' cells).');
  }
  const tiling = tilings[0];
  function literal(value, depth = 1) {
    const indent = "    ".repeat(depth);
    const nextIndent = "    ".repeat(depth + 1);
    if (value === null) return 'Nothing';
    if (typeof value === 'boolean') return value ? 'True' : 'False';
    if (typeof value === 'number') {
      if (!Number.isFinite(value)) throw new Error('Non-finite geometry');
      return value < 0 ? '(' + value + ')' : String(value);
    }
    if (typeof value === 'string') return JSON.stringify(value);
    if (Array.isArray(value)) return '[ ' + value.map(child => literal(child, depth + 1)).join('\n' + indent + ', ') + '\n' + indent + ']';
    return '{ ' + Object.entries(value).map(([key, child]) => {
      let expression = literal(child, depth + 1);
      if (['constraint', 'input', 'constant'].includes(key) && child !== null) expression = '(Just (' + expression + '))';
      if (key === 'outlines') expression = '(Dict.fromList [ ' + child.map(([id, outline]) => '(' + literal(id) + ', ' + literal(outline) + ')').join('\n' + nextIndent + ', ') + '\n' + indent + ' ])';
      return key + ' = ' + expression;
    }).join('\n' + indent + ', ') + '\n' + indent + '}';
  }
  const target = path.join(root, 'src/Generated/DefaultTiling.elm');
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, `module Generated.DefaultTiling exposing (tiling)

{-| Generated by build/generate-default.mjs. Rebuild rather than editing. -}

import Dict
import GenerativeTiling exposing (Tiling)


tiling : Tiling
tiling =
    ${literal(tiling)}
`);
  fs.writeFileSync(path.join(root, 'src/Generated/ExampleTilings.elm'), `module Generated.ExampleTilings exposing (get)

{-| Generated by build/generate-default.mjs. -}
import Dict
import Generated.DefaultTiling
import GenerativeTiling exposing (Tiling)

get : String -> Maybe Tiling
get source =
    case source of
        "!(a & b)" ->
            Just Generated.DefaultTiling.tiling

${examples.slice(1).map((source, i) => '        ' + JSON.stringify(source) + ' ->\n            Just\n                ' + literal(tilings[i + 1]).replaceAll('\n', '\n            ')).join('\n\n')}

        _ ->
            Nothing
`);
} finally {
  fs.rmSync(temporary, { recursive: true, force: true });
}
